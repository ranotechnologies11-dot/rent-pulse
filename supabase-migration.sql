create policy if not exists "service role full access properties" on public.properties for all to service_role using (true) with check (true);
create policy if not exists "service role full access tenants" on public.tenants for all to service_role using (true) with check (true);
create policy if not exists "service role full access invoices" on public.invoices for all to service_role using (true) with check (true);
create policy if not exists "service role full access payments" on public.payments for all to service_role using (true) with check (true);
create policy if not exists "service role full access reminder logs" on public.reminder_logs for all to service_role using (true) with check (true);
create policy if not exists "service role full access reminder settings" on public.reminder_settings for all to service_role using (true) with check (true);
